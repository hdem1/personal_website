        <h4>Results:</h4>

        <p>We built a functioning robot to compete in the 2019 and 2021 challenges (2020 was cancelled due to Covid-19). In the 2021 competition, our team won the <strong>Engineering Design Award</strong> in the 2021 Game Design Challenge.</p>

        <h4>Technical Overview:</h4>
          <p> For this project, the team developed a 4 foot tall robot which was able to complete several objectives in the First Robotics Competition. These objectives changed from year to year, but over my years on the team, these challenges included anything from elevating our robot onto a platform, shooting balls into various targets, removing plates from a wall, and completing autonomous challenge. In order to accomplish this, our robot needed to have a robust mechanical structure, a reliable electrical system, and an extensive code base. For example, our 2021 robot had a modified 4-wheeled drive train powered by 4 electric motors, a ball shooter using a high speed snowblower motor, a live-streamed onboard camera, and a power distribution system. </p>

        <h4>Project Process:</h4>

            <p>In 2018 during my sophomore year of high school, I was a founding member of a First Robotics Team (Team 7759 - linked) that quickly became a central focus of my high school experience. This team started with a small group working long evenings in the basement of one of the initial team leads to build a robot from scratch with no previous experience. I began as the Head Programmer and programmed our robot’s entire control system, but with so few people, my role quickly expanded to being a leader who was familiar with almost any part of our robot. Although that first season didn’t result in a victory at the competition, it was a thrilling immersion into the world of engineering, robotics, and computer science.</p> 

            <p>During my second year on the team, I got some great opportunities to work with a professional engineer and use more advanced tools as our team moved out of the basement and into a classroom at my high school. I was able to learn a lot more about engineering, and the team grew in many ways during this year, until it was unfortunately cut short just a week before the competition by the onset of Covid-19. This was a crushing blow to all of us who had poured hundreds of hours into this team, but I am still very proud of the robot that we were able to build and the skills that we were able to learn.</p>

            <p>I think that my final year on the team was the most transformative for me as a leader. I was made a captain of the entire team, meaning that I now had to assume responsibility for the technical, financial, and organizational management of the team. I had to learn the best ways to communicate with members so that technical objectives are achieved while still maintaining a fun club community. Interacting with part vendors, school administrators, and potential sponsors were all invaluable experiences that improved my confidence going into college. In general, FRC was likely the project that set me on a path towards engineering and computer science, and I am very proud of all that my team was able to accomplish.</p> 


