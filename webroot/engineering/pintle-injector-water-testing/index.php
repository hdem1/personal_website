        <h4>Project Process:</h4>

    <p>This engineering challenge was the first goal of Project Liquid, a club within the Yale Undergraduate Aerospace Association focused on developing liquid propulsion technology here at Yale. I was very excited about the team and immediately jumped into a leadership preposition as the Thrust Chamber Subteam Lead. To begin the club’s design process, it was decided that we would take on a simpler and more approachable task than a complete liquid rocket engine. To this end, we reached a water-based, gravity-fed design which would give us some experience with the concepts and design tools involved with making an engine.</p>

    <p>To begin this project, we conducted a substantial amount of research about everything involved. We learned fluid mechanics in the form of mass flow equations and Bernoulli’s equations. We practiced CAD modeling in solidworks. And, lastly, we heavily researched different types of propellant injectors. Looking at showerhead, impinging, coaxial swirl, pintle, and many other types of injectors, we gained a basic understanding of the benefits and drawbacks of each design. In the end, we decided to create a pintle injector because it appeared to have considerable benefits and be frequently used in industry. This also improved manufacturing because it required substantially less precise machining.</p>

    <p>Once we had decided upon the pintle injector, I led my team through the design process, creating models on a 3D printer and then testing their performance. Although the lack of a fluid supply apparatus made it difficult to test quantitatively, qualitative testing allowed us to hone in on a design that resulted in slight atomization of the liquid. This design was also focused on manufacturability with it being made of 3 parts that could be easily 3D printed and then slid together. In general, I think that this process of researching, designing, building, and testing was very valuable, and this exploration of the theory behind rocket engine injectors was great preparation for future projects.</p>



