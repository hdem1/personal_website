    <h1 class="pb-4">Mechanical Engineering Internship : Astrobotic Technology</h1>
    
<p><strong>Company Overview:</strong> Astrobotic Technologies is a company in Pittsburgh, Pennsylvania which builds lunar landers and rovers. At the time of writing this, the company’s first lander Peregrine is scheduled to launch in December 2024, and a larger lander Griffin is slated to launch in the next few years. In addition to landers, the company also builds a number of rovers, including the modular and customer-adaptable CubeRover. The company’s vision is focused on improving access to space, and it also does a lot of good work with the Pittsburgh community, including having a “Moon Museum” in the front of its headquarters.</p>

<p><strong>Role Overview:</strong> I worked as a Mechanical Engineering Intern within the Lunar Surface Systems department of Astrobotic. This meant that my job involved the design, manufacturing, and analysis of parts that would either be used on landers or used to test landers.</p>
