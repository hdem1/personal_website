<p>In general, my summer at Astrobotic was an extremely valuable experience for me both in terms of developing my technical skills and growing generally as an engineer. Thus, in addition to improving my CAD modeling skills and my manufacturing drawings, I also learned a lot about how to effectively communicate ideas, communicate with other professionals, and document the work I had done for effective transfer of knowledge. I was also exposed for the first time to the NASA proposal framework, including concepts such as Technology Readiness Level (TRL) and the different stages of grants. My mentor and the generally supportive atmosphere at Astrobotic helped me grow significantly over the course of the summer and come back to school with a lot of skills that I hadn’t had when I left.</p>
    
